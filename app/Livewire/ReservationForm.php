<?php

namespace App\Livewire;

use Livewire\Component;

class ReservationForm extends Component
{
    /*
    |--------------------------------------------------------------------------
    | フォームに入力された値を保存するプロパティ
    |--------------------------------------------------------------------------
    |
    | Blade側の wire:model と接続します。
    |
    | 例：
    |
    | <input wire:model="name">
    |
    | とすると、入力された内容が $name に入ります。
    |
    */

    // 予約者名
    public $name = '';

    // 人数
    public $people = 1;

    // 使用する席
    public $seat = '';

    // 予約開始時間
    public $startTime = '';

    // 予約終了時間
    public $endTime = '';


    /*
    |--------------------------------------------------------------------------
    | 席の選択肢
    |--------------------------------------------------------------------------
    |
    | ReservationStatus.php と同じ席を用意しています。
    | 後でデータベースを使うようになったら、
    | seatsテーブルなどから取得する形に変更できます。
    |
    */

    public $seats = [
        'テーブルA',
        'テーブルB',
        'テーブルC',
        '座席A',
        '座席B',
        'カウンターA',
        'カウンターB',
        'カウンターC',
        'カウンターD',
        'カウンターE',
    ];


    /*
    |--------------------------------------------------------------------------
    | 時間の選択肢
    |--------------------------------------------------------------------------
    |
    | 現在の予約状況画面と同じ30分単位の時間です。
    |
    */

    public $times = [
        '17:00',
        '17:30',
        '18:00',
        '18:30',
        '19:00',
        '19:30',
        '20:00',
        '20:30',
        '21:00',
        '21:30',
        '22:00',
    ];


    /*
    |--------------------------------------------------------------------------
    | バリデーション
    |--------------------------------------------------------------------------
    |
    | 登録ボタンが押されたときに、
    | 入力内容が正しいか確認するためのルールです。
    |
    */

    protected function rules()
    {
        return [
            // 名前は必須・文字列・最大50文字
            'name' => 'required|string|max:50',

            // 人数は必須・整数・1人以上
            'people' => 'required|integer|min:1',

            // 席は必須
            'seat' => 'required',

            // 開始時間は必須
            'startTime' => 'required',

            // 終了時間は必須
            'endTime' => 'required',
        ];
    }


    /*
    |--------------------------------------------------------------------------
    | 新規予約登録
    |--------------------------------------------------------------------------
    |
    | Blade側で
    |
    | wire:submit="save"
    |
    | と指定することで、このメソッドが実行されます。
    |
    */

    public function save()
    {
        // 入力チェック
        $this->validate();

        // 開始時間と終了時間の位置を取得
        $startIndex = array_search($this->startTime, $this->times);
        $endIndex = array_search($this->endTime, $this->times);

        // 終了時間が開始時間以前ならエラー
        if ($endIndex <= $startIndex) {
            $this->addError(
                'endTime',
                '終了時間は開始時間より後にしてください。'
            );

            return;
        }


        /*
    |--------------------------------------------------------------------------
    | ReservationStatusへ予約情報を送る
    |--------------------------------------------------------------------------
    |
    | dispatch() はLivewireのイベントを発生させます。
    |
    | 今回は
    |
    | reservation-created
    |
    | という名前のイベントを作っています。
    |
    | seat、startTimeなどがイベントと一緒に
    | ReservationStatusへ送られます。
    |
    */

        $this->dispatch(
            'reservation-created',
            seat: $this->seat,
            startTime: $this->startTime,
            endTime: $this->endTime,
            name: $this->name,
            people: $this->people,
        );


        // 登録完了メッセージ
        session()->flash(
            'message',
            '予約を登録しました。'
        );


        /*
     * 登録後にフォームを空に戻します。
     */
        $this->reset([
            'name',
            'seat',
            'startTime',
            'endTime',
        ]);

        // 人数は1人に戻す
        $this->people = 1;
    }


    /*
    |--------------------------------------------------------------------------
    | Bladeを表示
    |--------------------------------------------------------------------------
    */

    public function render()
    {
        return view('livewire.reservation-form');
    }
}
